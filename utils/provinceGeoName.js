/**
 * 把记录里的省份写法规范成地图 GeoJSON 名称；无法识别则返回空串。
 */
export function normalizeProvinceGeoName(input) {
  const raw = String(input || '').trim();
  if (!raw) return '';
  if (GEO_SET.has(raw)) return raw;
  if (ALIAS_TO_GEO[raw]) return ALIAS_TO_GEO[raw];

  // 「浙江省杭州市」等：取前缀命中
  for (const geo of GEO_PROVINCE_NAMES) {
    if (raw.startsWith(geo) || geo.startsWith(raw)) return geo;
  }
  for (const [alias, geo] of Object.entries(ALIAS_TO_GEO)) {
    if (raw.startsWith(alias)) return geo;
  }
  return '';
}
