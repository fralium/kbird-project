function canonicalizeBirdName(name) {
  const raw = String(name || '').trim();
  if (!raw) return '';
  return BIRD_NAME_ALIASES[raw] || raw;
}

function aliasKeysForCanonical(canonicalName) {
  const canonical = String(canonicalName || '').trim();
  if (!canonical) return [];
  return Object.entries(BIRD_NAME_ALIASES)
    .filter(([, main]) => main === canonical)
    .map(([alias]) => alias);
}

