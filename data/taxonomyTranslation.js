// 获取目的拉丁名（若传入已是拉丁则原样返回）
export const getOrderLatinName = (chineseOrLatin) => {
  if (!chineseOrLatin) return '';
  if (orderTranslation[chineseOrLatin]) return chineseOrLatin;
  if (orderChineseAliases[chineseOrLatin]) return orderChineseAliases[chineseOrLatin];
  const found = Object.entries(orderTranslation).find(([, cn]) => cn === chineseOrLatin);
  return found ? found[0] : '';
};

// 获取目的中文名（支持别名反查，如 啄木鸟目 → 鴷形目）
export const getOrderChineseName = (latinOrChinese) => {
  if (!latinOrChinese) return '';
  if (orderTranslation[latinOrChinese]) return orderTranslation[latinOrChinese];
  const latin = getOrderLatinName(latinOrChinese);
  if (latin && orderTranslation[latin]) return orderTranslation[latin];
  return latinOrChinese;
};

// 获取科的中文名（拉丁或中文均可）
export const getFamilyChineseName = (latinOrChinese) => {
  if (!latinOrChinese) return '';
  if (familyTranslation[latinOrChinese]) return familyTranslation[latinOrChinese];
  const found = Object.entries(familyTranslation).find(([, cn]) => cn === latinOrChinese);
  return found ? found[1] : latinOrChinese;
};

// 获取科的拉丁名（若传入已是拉丁则原样返回）
export const getFamilyLatinName = (chineseOrLatin) => {
  if (!chineseOrLatin) return '';
  if (familyTranslation[chineseOrLatin]) return chineseOrLatin;
  const found = Object.entries(familyTranslation).find(([, cn]) => cn === chineseOrLatin);
  return found ? found[0] : '';
};

// 格式化分类显示：中文名/拉丁名
export const formatTaxonomyDisplay = (chineseName, latinName) => {
  if (!chineseName || chineseName === latinName) {
    return latinName;
  }
  return `${chineseName}/${latinName}`;
};










