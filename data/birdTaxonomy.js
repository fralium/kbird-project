// 获取所有目
export const getOrders = () => {
  return Object.keys(birdTaxonomy);
};

// 根据目获取科
export const getFamilies = (order) => {
  if (!order || !birdTaxonomy[order]) {
    return [];
  }
  return Object.keys(birdTaxonomy[order]);
};

// 根据目和科获取属
export const getGenera = (order, family) => {
  if (!order || !family || !birdTaxonomy[order] || !birdTaxonomy[order][family]) {
    return [];
  }
  return Object.keys(birdTaxonomy[order][family]);
};

// 根据目、科、属获取种
export const getSpecies = (order, family, genus) => {
  if (!order || !family || !genus || 
      !birdTaxonomy[order] || 
      !birdTaxonomy[order][family] || 
      !birdTaxonomy[order][family][genus]) {
    return [];
  }
  return birdTaxonomy[order][family][genus];
};

// 构建完整的分类路径
export const buildTaxonomyPath = (order, family, genus, species) => {
  const path = [];
  if (order) path.push(order);
  if (family) path.push(family);
  if (genus) path.push(genus);
  if (species) path.push(species);
  return path.join(' > ');
};

// 解析分类路径
export const parseTaxonomyPath = (path) => {
  if (!path) return { order: '', family: '', genus: '', species: '' };
  
  const parts = path.split(' > ');
  return {
    order: parts[0] || '',
    family: parts[1] || '',
    genus: parts[2] || '',
    species: parts[3] || ''
  };
};

// 搜索分类（模糊匹配）
export const searchTaxonomy = (query) => {
  if (!query) return [];
  
  const results = [];
  const lowerQuery = query.toLowerCase();
  
  // 搜索目
  for (const order of getOrders()) {
    if (order.toLowerCase().includes(lowerQuery)) {
      results.push({
        type: 'order',
        value: order,
        path: order
      });
    }
    
    // 搜索科
    for (const family of getFamilies(order)) {
      if (family.toLowerCase().includes(lowerQuery)) {
        results.push({
          type: 'family',
          value: family,
          path: `${order} > ${family}`
        });
      }
      
      // 搜索属
      for (const genus of getGenera(order, family)) {
        if (genus.toLowerCase().includes(lowerQuery)) {
          results.push({
            type: 'genus',
            value: genus,
            path: `${order} > ${family} > ${genus}`
          });
        }
        
        // 搜索种
        for (const species of getSpecies(order, family, genus)) {
          if (species.toLowerCase().includes(lowerQuery)) {
            results.push({
              type: 'species',
              value: species,
              path: `${order} > ${family} > ${genus} > ${species}`
            });
          }
        }
      }
    }
  }
  
  return results;
};

// 获取分类数据（用于TaxonomySelector组件）
export const getTaxonomyData = () => {
  const orders = getOrders();
  const families = {};
  const genera = {};
  const species = {};
  
  // 构建科数据
  orders.forEach(order => {
    families[order] = getFamilies(order);
  });
  
  // 构建属数据
  orders.forEach(order => {
    const orderFamilies = getFamilies(order);
    orderFamilies.forEach(family => {
      const familyKey = `${order}_${family}`;
      genera[familyKey] = getGenera(order, family);
    });
  });
  
  // 构建种数据
  orders.forEach(order => {
    const orderFamilies = getFamilies(order);
    orderFamilies.forEach(family => {
      const orderGenera = getGenera(order, family);
      orderGenera.forEach(genus => {
        const genusKey = `${order}_${family}_${genus}`;
        species[genusKey] = getSpecies(order, family, genus);
      });
    });
  });
  
  return {
    orders,
    families,
    genera,
    species
  };
};

